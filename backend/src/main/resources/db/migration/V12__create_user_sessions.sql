--
-- Session persistence (V12) — one row per issued session token. Only the SHA-256 hash of the
-- token is stored; the raw token lives in the HttpOnly session cookie. Every sign-in starts a
-- new family (one device's chain of rotated tokens). Revocation deletes rows: a family on
-- logout or replay, every row of a user on password reset. Mirrors V10's conventions.
--

CREATE TABLE public.user_sessions (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    family_id uuid NOT NULL,
    token_hash character varying(64) NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    replaced_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.user_sessions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.user_sessions_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.user_sessions
    ADD CONSTRAINT user_sessions_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.user_sessions
    ADD CONSTRAINT uk_user_sessions_token_hash UNIQUE (token_hash);

ALTER TABLE ONLY public.user_sessions
    ADD CONSTRAINT fk_user_sessions_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

CREATE INDEX idx_user_sessions_user_id ON public.user_sessions USING btree (user_id);

CREATE INDEX idx_user_sessions_family_id ON public.user_sessions USING btree (family_id);
