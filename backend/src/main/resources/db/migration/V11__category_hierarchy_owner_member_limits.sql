--
-- Categories revamp (V11) — two-level category hierarchy (parent_id), optional category owner
-- (owner_user_id) and per-member category limits (category_member_limits). Existing categories
-- become roots with no owner and no member limits, so behavior is unchanged on deploy.
-- SPEC_DEVIATION: design.md names this file V10__...; V10 is already taken by
-- V10__create_password_reset_tokens.sql, so the next free version (V11) is used.
-- Pure SQL only. Mirrors the conventions of V6/V7 (bigint IDENTITY PKs, numeric(38,2) amounts).
--

ALTER TABLE public.financial_transaction_categories
    ADD COLUMN parent_id bigint,
    ADD COLUMN owner_user_id bigint;

ALTER TABLE ONLY public.financial_transaction_categories
    ADD CONSTRAINT fk_ftc_parent FOREIGN KEY (parent_id) REFERENCES public.financial_transaction_categories(id);

ALTER TABLE ONLY public.financial_transaction_categories
    ADD CONSTRAINT fk_ftc_owner FOREIGN KEY (owner_user_id) REFERENCES public.users(id);

CREATE INDEX idx_ftc_parent ON public.financial_transaction_categories USING btree (parent_id);


--
-- Name: category_member_limits; Type: TABLE; Schema: public; Owner: -
--

CREATE TABLE public.category_member_limits (
    id bigint NOT NULL,
    category_id bigint NOT NULL,
    member_user_id bigint NOT NULL,
    amount numeric(38,2) NOT NULL,
    CONSTRAINT ck_cml_amount_non_negative CHECK ((amount >= (0)::numeric))
);


ALTER TABLE public.category_member_limits ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.category_member_limits_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);


ALTER TABLE ONLY public.category_member_limits
    ADD CONSTRAINT category_member_limits_pkey PRIMARY KEY (id);


ALTER TABLE ONLY public.category_member_limits
    ADD CONSTRAINT uk_cml_category_member UNIQUE (category_id, member_user_id);


ALTER TABLE ONLY public.category_member_limits
    ADD CONSTRAINT fk_cml_category FOREIGN KEY (category_id) REFERENCES public.financial_transaction_categories(id) ON DELETE CASCADE;


ALTER TABLE ONLY public.category_member_limits
    ADD CONSTRAINT fk_cml_member FOREIGN KEY (member_user_id) REFERENCES public.users(id);


CREATE INDEX idx_cml_category ON public.category_member_limits USING btree (category_id);
